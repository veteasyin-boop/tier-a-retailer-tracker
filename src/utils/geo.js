export function calculateDistanceKm(lat1, lon1, lat2, lon2) {
  const R = 6371; // Earth radius in km
  const dLat = (lat2 - lat1) * Math.PI / 180;
  const dLon = (lon2 - lon1) * Math.PI / 180;
  const a = Math.sin(dLat / 2) * Math.sin(dLat / 2) +
            Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) *
            Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

export function findClosestBlocks(userLat, userLng) {
  const sorted = BIHAR_BLOCKS.map(b => ({
    ...b,
    distanceKm: calculateDistanceKm(userLat, userLng, b.lat, b.lng)
  })).sort((a, b) => a.distanceKm - b.distanceKm);

  return sorted;
}

export function detectBrowserLocation(options = {}) {
  const timeoutMs = options.timeout || 7000;
  const maxAge = options.maximumAge !== undefined ? options.maximumAge : 15000;

  return new Promise((resolve) => {
    if (typeof navigator === 'undefined' || !navigator.geolocation) {
      resolve({ success: false, error: 'Geolocation not supported by device' });
      return;
    }

    let resolved = false;
    const finish = (result) => {
      if (!resolved) {
        resolved = true;
        resolve(result);
      }
    };

    // Overall timeout guard
    const overallTimer = setTimeout(() => {
      finish({ success: false, error: 'GPS request timed out' });
    }, timeoutMs + 500);

    const tryLowAccuracy = () => {
      navigator.geolocation.getCurrentPosition(
        (pos) => {
          clearTimeout(overallTimer);
          finish({
            success: true,
            lat: pos.coords.latitude,
            lng: pos.coords.longitude,
            accuracy: Math.round(pos.coords.accuracy || 100),
            altitude: pos.coords.altitude || null,
            heading: pos.coords.heading || null,
            speed: pos.coords.speed || null,
            timestamp: pos.timestamp || Date.now(),
            source: 'network'
          });
        },
        (err) => {
          clearTimeout(overallTimer);
          finish({ success: false, error: err.message || 'Position unavailable' });
        },
        { enableHighAccuracy: false, timeout: Math.max(3000, timeoutMs - 3000), maximumAge: maxAge }
      );
    };

    // Attempt high accuracy; if it fails or takes > 3.5s (common on laptops without GPS hardware), fallback to network
    const highAccuracyTimer = setTimeout(() => {
      if (!resolved) {
        tryLowAccuracy();
      }
    }, 3500);

    navigator.geolocation.getCurrentPosition(
      (pos) => {
        clearTimeout(highAccuracyTimer);
        clearTimeout(overallTimer);
        finish({
          success: true,
          lat: pos.coords.latitude,
          lng: pos.coords.longitude,
          accuracy: Math.round(pos.coords.accuracy || 20),
          altitude: pos.coords.altitude || null,
          heading: pos.coords.heading || null,
          speed: pos.coords.speed || null,
          timestamp: pos.timestamp || Date.now(),
          source: 'gps'
        });
      },
      (err) => {
        clearTimeout(highAccuracyTimer);
        if (!resolved) {
          tryLowAccuracy();
        }
      },
      { timeout: 3500, enableHighAccuracy: true, maximumAge: maxAge }
    );
  });
}

export function escapeHtml(str) {
  return String(str || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

export function resolveCoordinates(item) {
  if (item && item.lat && item.lng) {
    return { lat: Number(item.lat), lng: Number(item.lng) };
  }
  if (item && item.checkInCoords && item.checkInCoords.lat && item.checkInCoords.lng) {
    return { lat: Number(item.checkInCoords.lat), lng: Number(item.checkInCoords.lng) };
  }
  // Lookup block centroid
  const blockName = item?.block || '';
  const match = BIHAR_BLOCKS.find(b => b.block.toLowerCase() === blockName.toLowerCase());
  if (match) {
    // Deterministic micro-offset based on retailer ID or name to prevent identical points
    const hash = (item.id || item.retailer || '').split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
    const offsetLat = ((hash % 17) - 8) * 0.003;
    const offsetLng = (((hash * 7) % 17) - 8) * 0.003;
    return { 
      lat: Math.round((match.lat + offsetLat) * 10000) / 10000, 
      lng: Math.round((match.lng + offsetLng) * 10000) / 10000 
    };
  }
  return { lat: 25.564, lng: 84.868 }; // Default Bihta HQ
}

export function optimizeTourBeatRoute(startCoords, rawStops, options = {}) {
  const returnToHq = options.returnToHq !== false;
  const avgBikeSpeedKmh = options.avgSpeedKmh || 32; // Bihar rural bike average speed
  const visitMinutesPerStop = options.visitMinutesPerStop || 25;

  if (!rawStops || rawStops.length === 0) {
    return {
      orderedStops: [],
      legs: [],
      totalDistanceKm: 0,
      totalDrivingMinutes: 0,
      totalVisitMinutes: 0,
      totalShiftMinutes: 0,
      googleMapsUrl: '',
      startCoords
    };
  }

  // Prepare stops with resolved coordinates
  const pool = rawStops.map((stop, idx) => {
    const coords = resolveCoordinates(stop);
    return {
      ...stop,
      _originalIndex: idx,
      lat: coords.lat,
      lng: coords.lng
    };
  });

  const orderedStops = [];
  const legs = [];
  let currentPos = { lat: startCoords.lat, lng: startCoords.lng, label: startCoords.name || 'Station HQ' };
  let remaining = [...pool];
  let totalDistanceKm = 0;
  let totalDrivingMinutes = 0;

  let sequenceNum = 1;
  while (remaining.length > 0) {
    // Find nearest neighbor to currentPos
    let nearestIdx = 0;
    let nearestDist = calculateDistanceKm(currentPos.lat, currentPos.lng, remaining[0].lat, remaining[0].lng);

    for (let i = 1; i < remaining.length; i++) {
      const dist = calculateDistanceKm(currentPos.lat, currentPos.lng, remaining[i].lat, remaining[i].lng);
      if (dist < nearestDist) {
        nearestDist = dist;
        nearestIdx = i;
      }
    }

    const nextStop = remaining.splice(nearestIdx, 1)[0];
    // Rural road curvature factor ~1.28
    const roadDistKm = Math.round(nearestDist * 1.28 * 10) / 10;
    const driveMins = Math.max(4, Math.round((roadDistKm / avgBikeSpeedKmh) * 60));

    legs.push({
      legNumber: sequenceNum,
      from: currentPos.label || currentPos.retailer || 'Station HQ',
      to: nextStop.retailer,
      fromCoords: { lat: currentPos.lat, lng: currentPos.lng },
      toCoords: { lat: nextStop.lat, lng: nextStop.lng },
      aerialKm: nearestDist,
      roadKm: roadDistKm,
      driveMinutes: driveMins
    });

    totalDistanceKm += roadDistKm;
    totalDrivingMinutes += driveMins;

    orderedStops.push({
      ...nextStop,
      sequenceOrder: sequenceNum,
      legDistanceKm: roadDistKm,
      legDriveMinutes: driveMins,
      estimatedArrivalOffsetMins: totalDrivingMinutes + ((sequenceNum - 1) * visitMinutesPerStop)
    });

    currentPos = { ...nextStop, label: nextStop.retailer };
    sequenceNum++;
  }

  // Return to HQ leg
  if (returnToHq && orderedStops.length > 0) {
    const returnAerial = calculateDistanceKm(currentPos.lat, currentPos.lng, startCoords.lat, startCoords.lng);
    const returnRoadKm = Math.round(returnAerial * 1.28 * 10) / 10;
    const returnDriveMins = Math.max(5, Math.round((returnRoadKm / avgBikeSpeedKmh) * 60));

    legs.push({
      legNumber: sequenceNum,
      from: currentPos.retailer || 'Last Stop',
      to: startCoords.name || 'Station HQ (Return)',
      fromCoords: { lat: currentPos.lat, lng: currentPos.lng },
      toCoords: { lat: startCoords.lat, lng: startCoords.lng },
      aerialKm: returnAerial,
      roadKm: returnRoadKm,
      driveMinutes: returnDriveMins,
      isReturnLeg: true
    });

    totalDistanceKm += returnRoadKm;
    totalDrivingMinutes += returnDriveMins;
  }

  totalDistanceKm = Math.round(totalDistanceKm * 10) / 10;
  const totalVisitMinutes = orderedStops.length * visitMinutesPerStop;
  const totalShiftMinutes = totalDrivingMinutes + totalVisitMinutes;

  // Build Google Maps Multi-Stop Navigation URL
  const originStr = `${startCoords.lat},${startCoords.lng}`;
  const destStr = returnToHq ? originStr : `${orderedStops[orderedStops.length - 1].lat},${orderedStops[orderedStops.length - 1].lng}`;
  const waypoints = (returnToHq ? orderedStops : orderedStops.slice(0, -1))
    .slice(0, 9) // Google Maps URL API limit for waypoints
    .map(s => `${s.lat},${s.lng}`)
    .join('|');

  const googleMapsUrl = `https://www.google.com/maps/dir/?api=1&origin=${encodeURIComponent(originStr)}&destination=${encodeURIComponent(destStr)}${waypoints ? `&waypoints=${encodeURIComponent(waypoints)}` : ''}&travelmode=driving`;

  return {
    orderedStops,
    legs,
    totalDistanceKm,
    totalDrivingMinutes,
    totalVisitMinutes,
    totalShiftMinutes,
    googleMapsUrl,
    startCoords
  };
}

export function calculateCheckInJourneyKm(checkInLogs, hqCoords) {
  if (!checkInLogs || checkInLogs.length === 0) {
    return {
      legs: [],
      totalRoadKm: 0,
      totalAerialKm: 0,
      stopCount: 0
    };
  }

  // Sort logs chronologically
  const sorted = [...checkInLogs].sort((a, b) => (a.timestamp || 0) - (b.timestamp || 0));

  let prevPos = hqCoords ? { lat: hqCoords.lat, lng: hqCoords.lng, name: hqCoords.name || 'HQ Station' } : null;
  const legs = [];
  let totalAerialKm = 0;
  let totalRoadKm = 0;

  for (let i = 0; i < sorted.length; i++) {
    const curr = sorted[i];
    const currLat = curr.lat || curr.checkInCoords?.lat;
    const currLng = curr.lng || curr.checkInCoords?.lng;

    if (currLat && currLng) {
      if (prevPos) {
        const aerial = calculateDistanceKm(prevPos.lat, prevPos.lng, currLat, currLng);
        const roadKm = Math.round(aerial * 1.28 * 10) / 10;
        legs.push({
          from: prevPos.name || 'Stop',
          to: curr.retailer || 'Counter',
          aerialKm: aerial,
          roadKm: roadKm,
          time: curr.time || ''
        });
        totalAerialKm += aerial;
        totalRoadKm += roadKm;
      }
      prevPos = { lat: currLat, lng: currLng, name: curr.retailer };
    }
  }

  // Add return leg to HQ if HQ provided
  if (hqCoords && prevPos && sorted.length > 0) {
    const returnAerial = calculateDistanceKm(prevPos.lat, prevPos.lng, hqCoords.lat, hqCoords.lng);
    const returnRoadKm = Math.round(returnAerial * 1.28 * 10) / 10;
    legs.push({
      from: prevPos.name || 'Last Counter',
      to: hqCoords.name || 'HQ Station (Return)',
      aerialKm: returnAerial,
      roadKm: returnRoadKm,
      isReturnLeg: true
    });
    totalAerialKm += returnAerial;
    totalRoadKm += returnRoadKm;
  }

  totalAerialKm = Math.round(totalAerialKm * 10) / 10;
  totalRoadKm = Math.round(totalRoadKm * 10) / 10;

  return {
    legs,
    totalAerialKm,
    totalRoadKm,
    stopCount: sorted.length
  };
}

